#!/usr/bin/env bash
# Concatenate the public theme CSS/JS used by the main layout into single files,
# so pages make 2 requests instead of ~20. bundle-home.js is a lighter build for
# the homepage, which uses none of the grid/popup plugins. Re-run after editing
# any listed file:
#   bin/bundle-assets.sh
set -euo pipefail
cd "$(dirname "$0")/../public/assets"

CSS_FILES=(bootstrap.min.css slick.css slick-theme.css global.css twenty.css reset.css style.css)
JS_FILES=(jquery.min.js popper.min.js bootstrap.min.js jquery.magnific-popup.min.js appear.js slick.js
    jquery.counterup.min.js waypoints.min.js isotope.pkgd.min.js twenty.js imagesloaded.pkgd.min.js
    masonry.pkgd.min.js wow.min.js jquery.inputarrow.js script.js)
HOME_JS_FILES=(jquery.min.js bootstrap.min.js slick.js jquery.counterup.min.js waypoints.min.js twenty.js
    wow.min.js plugin-fallbacks.js script.js)

{
    echo '@charset "UTF-8";'
    echo '/* Generated by bin/bundle-assets.sh - do not edit. */'
    for f in "${CSS_FILES[@]}"; do
        echo "/* ---- $f ---- */"
        # @charset is only valid as the very first rule of a stylesheet.
        sed -E 's/@charset[^;]*;//; /sourceMappingURL/d' "css/$f"
        echo
    done
} > css/bundle.css

bundle_js() {
    local out=$1
    shift
    {
        echo '/* Generated by bin/bundle-assets.sh - do not edit. */'
        for f in "$@"; do
            echo "/* ---- $f ---- */"
            sed '/^\/\/# sourceMappingURL/d' "js/$f"
            # Guard against files that end without a semicolon or newline.
            printf '\n;\n'
        done
    } > "$out"
}

bundle_js js/bundle.js "${JS_FILES[@]}"
bundle_js js/bundle-home.js "${HOME_JS_FILES[@]}"

ls -l css/bundle.css js/bundle.js js/bundle-home.js
