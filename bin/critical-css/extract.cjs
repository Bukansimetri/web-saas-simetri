// Builds public/assets/css/critical-home.css: the bundle.css rules that style
// above-the-fold content on the homepage (mobile + desktop), plus the self-hosted
// Google Fonts. The layout inlines it and loads bundle.css without blocking render.
//
// Re-run after changing bundle.css or the top of the homepage:
//   npm i --no-save puppeteer-core@24
//   node bin/critical-css/extract.cjs https://livinginterior.id/
// Needs Google Chrome installed (CHROME_PATH overrides its location).
const puppeteer = require('puppeteer-core');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '../..');
const url = process.argv[2] || 'https://livinginterior.id/';
const outPath = process.argv[3] || path.join(root, 'public/assets/css/critical-home.css');
const VIEWPORTS = [
  { width: 412, height: 915, isMobile: true, deviceScaleFactor: 2 },
  { width: 1366, height: 900, isMobile: false, deviceScaleFactor: 1 },
];
const FOLD_MARGIN = 150;

function collect(foldHeight, margin) {
  const sheet = [...document.styleSheets].find(s => s.href && s.href.includes('/assets/css/bundle.css'));
  if (!sheet) throw new Error('bundle.css not found');
  const kept = [];
  const stripPseudo = sel => sel
    .replace(/::?(before|after|placeholder|selection|marker|first-letter|first-line|-webkit-[\w-]+|-moz-[\w-]+|-ms-[\w-]+)/g, '')
    .replace(/:(hover|focus|focus-within|focus-visible|active|visited|checked|disabled|enabled|target|invalid|valid|indeterminate|placeholder-shown|read-only|autofill)/g, '')
    .trim() || '*';
  const aboveFold = el => {
    const r = el.getBoundingClientRect();
    return r.top < foldHeight + margin;
  };
  const matches = selectorText => selectorText.split(',').some(part => {
    const sel = stripPseudo(part);
    try {
      const els = document.querySelectorAll(sel);
      for (const el of els) if (aboveFold(el)) return true;
    } catch (e) { return false; }
    return false;
  });
  const walk = (rules, path) => {
    [...rules].forEach((rule, i) => {
      const p = path.concat(i);
      if (rule.type === CSSRule.STYLE_RULE) {
        if (/^(html|body|:root|\*)/.test(rule.selectorText) || matches(rule.selectorText)) kept.push(p.join('.'));
      } else if (rule.type === CSSRule.MEDIA_RULE || rule.type === CSSRule.SUPPORTS_RULE) {
        walk(rule.cssRules, p);
      }
    });
  };
  walk(sheet.cssRules, []);
  return kept;
}

function render(keptList) {
  const kept = new Set(keptList);
  const sheet = [...document.styleSheets].find(s => s.href && s.href.includes('/assets/css/bundle.css'));
  const out = (rules, path) => {
    let css = '';
    [...rules].forEach((rule, i) => {
      const p = path.concat(i);
      if (rule.type === CSSRule.STYLE_RULE) {
        if (kept.has(p.join('.'))) css += rule.cssText + '\n';
      } else if (rule.type === CSSRule.MEDIA_RULE) {
        const inner = out(rule.cssRules, p);
        if (inner) css += '@media ' + rule.conditionText + '{\n' + inner + '}\n';
      } else if (rule.type === CSSRule.SUPPORTS_RULE) {
        const inner = out(rule.cssRules, p);
        if (inner) css += '@supports ' + rule.conditionText + '{\n' + inner + '}\n';
      }
    });
    return css;
  };
  return out(sheet.cssRules, []);
}

(async () => {
  const browser = await puppeteer.launch({
    executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    headless: true,
  });
  const all = new Set();
  let css = '';
  for (const vp of VIEWPORTS) {
    const page = await browser.newPage();
    await page.setViewport(vp);
    await page.goto(url + (url.includes('?') ? '&' : '?') + 'critical=' + Date.now(), { waitUntil: 'networkidle2', timeout: 60000 });
    await new Promise(r => setTimeout(r, 1500));
    const kept = await page.evaluate(collect, vp.height, FOLD_MARGIN);
    kept.forEach(k => all.add(k));
    console.log(vp.width, 'kept rules', kept.length);
    if (vp === VIEWPORTS[VIEWPORTS.length - 1]) css = await page.evaluate(render, [...all]);
    await page.close();
  }
  await browser.close();

  // Inlined CSS resolves URLs against the page, not /assets/css/.
  const absolutize = text => text.replace(/url\((["']?)\.\.\//g, 'url($1/assets/');
  const fonts = fs.readFileSync(path.join(root, 'public/assets/css/google-fonts.css'), 'utf8');
  css = '/* Above-the-fold CSS for the homepage, inlined by the layout. Generated by bin/critical-css - do not edit. */\n'
    + absolutize(fonts) + absolutize(css);
  fs.writeFileSync(outPath, css);
  console.log('total rules', all.size, 'bytes', css.length);
})().catch(e => { console.error(e); process.exit(1); });
